#pragma once

#include <cstdint>
#include <vector>

#include <glm/glm.hpp>

namespace geometry {

struct Vertex {
	glm::vec3 position;
	glm::vec3 normal;
	glm::vec2 uv;
};

struct Mesh {
	std::vector<Vertex> vertices;
	std::vector<uint16_t> indices;
};

// Правильный додекаэдр, вписанный в единичную сферу: 12 пятиугольных граней, каждая разбита на 3 треугольника.
// У каждой грани свои 5 вершин (всего 60), потому что нормаль у граней разная: освещение получается плоским, с чёткими рёбрами.
// Нормаль грани считается как векторное произведение рёбер её первого треугольника.
// Треугольники обходятся против часовой стрелки, если смотреть снаружи.
// Текстурные координаты: пятиугольник грани вписан в круг, вписанный в квадрат [0, 1]^2, и на каждой грани текстура
// лежит без зеркального отражения (при взгляде снаружи u растёт вправо, v вниз, как строки изображения).
Mesh makeDodecahedron();

// Квадрат [-1, 1] x [-1, 1] в плоскости XZ с нормалью +Y, обход против часовой стрелки при взгляде сверху.
// Текстурные координаты (x, z) -> ((x + 1) / 2, (z + 1) / 2): вся текстура ровно один раз.
Mesh makePlane();

// Куб [-1, 1]^3 с плоскими нормалями граней: 24 вершины и 36 индексов, обход против часовой стрелки снаружи.
// На каждой грани вся текстура целиком.
Mesh makeCube();

// Конус из линий для показа прожектора (топология LINE_LIST). Вершина конуса в начале координат, ось направлена вдоль -Z,
// окружность основания радиуса 1 лежит в плоскости z = -1. Ещё рисуются четыре образующие и ось. Нормали и текстурные координаты нулевые.
Mesh makeSpotCone();

} // namespace geometry
